from gtts import gTTS
from deep_translator import GoogleTranslator, MyMemoryTranslator
from deep_translator.exceptions import TooManyRequests

class SpeechSynthesis:
   def __init__(self, text="Hello, world!", target_lang="mr", source_lang="en"):
      self._text = text
      self._target_lang = target_lang
      self._source_lang = source_lang

   @property
   def text(self):
      return self._text

   @text.setter
   def text(self, value):
      self._text = value

   @property
   def target_lang(self):
      return self._target_lang

   @target_lang.setter
   def target_lang(self, value):
      self._target_lang = value

   @property
   def source_lang(self):
      return self._source_lang

   @source_lang.setter
   def source_lang(self, value):
      self._source_lang = value

   def translate_text(self):
      # Map short language codes to full names for MyMemory fallback if needed
      lang_mapping = {
          "en": "english",
          "mr": "marathi"
      }
      src = self.source_lang
      tgt = self.target_lang

      try:
         # Try Google Translate first
         translated = GoogleTranslator(source=src, target=tgt).translate(self.text)
         return translated
      except TooManyRequests:
         print("Google Translate rate limit hit! Falling back to MyMemory Translator...")
         # Resolve full names if abbreviations are passed
         mymemory_src = lang_mapping.get(src, src)
         mymemory_tgt = lang_mapping.get(tgt, tgt)
         translated = MyMemoryTranslator(source=mymemory_src, target=mymemory_tgt).translate(self.text)
         return translated

   def synthesize(self, filename="mr.mp3"):
      translated_text = self.translate_text()
      tts = gTTS(text=translated_text, lang=self.target_lang)
      tts.save(filename)
      print(f"Audio saved as '{filename}'")

# Example usage
synth = SpeechSynthesis(text="Hello, Am Thila gavathi can you say my name!", target_lang="mr")
synth.synthesize()

# Get properties
print(f"Original Text: {synth.text}")
print(f"Translated Text: {synth.translate_text()}")
print(f"Target Language: {synth.target_lang}")
print(f"Source Language: {synth.source_lang}")