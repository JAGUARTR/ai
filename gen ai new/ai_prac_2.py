#GAN
import torch
import torch.nn as nn
import torch.optim as optim
import torchvision
import torchvision.transforms as transforms
import matplotlib.pyplot as plt

# Use GPU if available; otherwise use CPU
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

print("PyTorch version:", torch.__version__)
print("Device selected:", device)

class Generator(nn.Module):
    def __init__(self):
        super(Generator, self).__init__()

        self.model = nn.Sequential(
            nn.Linear(100, 256),
            nn.ReLU(),

            nn.Linear(256, 784),
            nn.ReLU(),

            nn.Linear(784, 784),
            nn.Tanh()
        )

    def forward(self, x):
        return self.model(x).view(-1, 1, 28, 28)


generator = Generator().to(device)

print("Generator created successfully!")

class Discriminator(nn.Module):
    def __init__(self):
        super(Discriminator, self).__init__()

        self.model = nn.Sequential(
            nn.Flatten(),

            nn.Linear(784, 512),
            nn.LeakyReLU(0.2),

            nn.Linear(512, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        return self.model(x.view(-1, 784))


discriminator = Discriminator().to(device)

print("Discriminator created successfully!")

transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize((0.5,), (0.5,))
])

dataset = torchvision.datasets.MNIST(
    root="./data",
    train=True,
    transform=transform,
    download=True
)

dataloader = torch.utils.data.DataLoader(
    dataset,
    batch_size=64,
    shuffle=True
)

print("MNIST dataset loaded successfully!")
print("Number of training images:", len(dataset))

def train_gan(generator, discriminator, dataloader, num_epochs=5):
    criterion = nn.BCELoss()

    g_optimizer = optim.Adam(
        generator.parameters(),
        lr=0.0002,
        betas=(0.5, 0.999)
    )

    d_optimizer = optim.Adam(
        discriminator.parameters(),
        lr=0.0002,
        betas=(0.5, 0.999)
    )

    for epoch in range(num_epochs):
        for real_data, _ in dataloader:
            batch_size = real_data.size(0)
            real_data = real_data.to(device)

            real_labels = torch.ones(batch_size, 1, device=device)
            fake_labels = torch.zeros(batch_size, 1, device=device)

            # Train the Discriminator
            d_optimizer.zero_grad()

            real_output = discriminator(real_data)
            d_loss_real = criterion(real_output, real_labels)

            noise = torch.randn(batch_size, 100, device=device)
            fake_data = generator(noise)

            fake_output = discriminator(fake_data.detach())
            d_loss_fake = criterion(fake_output, fake_labels)

            d_loss = d_loss_real + d_loss_fake
            d_loss.backward()
            d_optimizer.step()

            # Train the Generator
            g_optimizer.zero_grad()

            fake_output = discriminator(fake_data)
            g_loss = criterion(fake_output, real_labels)

            g_loss.backward()
            g_optimizer.step()

        print(
            f"Epoch [{epoch + 1}/{num_epochs}], "
            f"D Loss: {d_loss.item():.4f}, "
            f"G Loss: {g_loss.item():.4f}"
        )


train_gan(generator, discriminator, dataloader, num_epochs=5)

def generate_images(generator, num_images=16):
    generator.eval()

    with torch.no_grad():
        noise = torch.randn(num_images, 100, device=device)
        generated_images = generator(noise)

        # Convert pixel range [-1, 1] to [0, 1]
        generated_images = (generated_images + 1) / 2

        grid = torchvision.utils.make_grid(
            generated_images.cpu(),
            nrow=4,
            normalize=False,
            padding=2
        )

    # Display the grid
    plt.figure(figsize=(7, 7))
    plt.imshow(grid.permute(1, 2, 0).squeeze(), cmap="gray")
    plt.title("GAN Generated MNIST Digits")
    plt.axis("off")
    plt.show()

    # Save the generated image grid
    torchvision.utils.save_image(
        grid,
        "generated_images.png"
    )

    print("Image saved as generated_images.png")


generate_images(generator)